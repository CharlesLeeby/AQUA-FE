    START="$2"; DURATION="$3"
    METHOD="${4:-$METHOD_DEFAULT}"
    EVERY_N="${5:-2}"
    TAG_STEM="ntnu_$(slugify "$DATASET")_s${START}_d${DURATION}"
    RUN_DIR_ROOT="$ROOT/logs/ntnu_vins"
    RUN_ARGS=(ntnu "$DATASET" "$START" "$DURATION")
    ;;
  cirs)
    START="${1:?cirs START_S DURATION_S [METHOD] [EVERY_N]}"
    DURATION="$2"
    METHOD="${3:-$METHOD_DEFAULT}"
    EVERY_N="${4:-1}"
    TAG_STEM="cirs_s${START}_d${DURATION}"
    RUN_DIR_ROOT="$ROOT/logs/cirs_caves_vins"
    RUN_ARGS=(cirs "$START" "$DURATION")
    ;;
  aqualoc_real)
    HARBOR_SEQ="$(normalize_harbor_seq "${1:?aqualoc_real HARBOR_SEQ START_INDEX END_INDEX [METHOD] [EVERY_N]}")"
    START="$2"; END="$3"
    METHOD="${4:-$METHOD_DEFAULT}"
    EVERY_N="${5:-2}"
    TAG_STEM="aqualoc_h$(printf "%02d" "$HARBOR_SEQ")_${START}_${END}"
    RUN_DIR_ROOT="$ROOT/logs/aqualoc_real_vins"
    RUN_ARGS=(aqualoc_real "$HARBOR_SEQ" "$START" "$END")
    ;;
  aqualoc_archaeo|aqualoc)
    SEQ="${1:?aqualoc_archaeo SEQ START_INDEX END_INDEX [METHOD] [EVERY_N]}"
    START="$2"; END="$3"
    METHOD="${4:-$METHOD_DEFAULT}"
    EVERY_N="${5:-2}"
    TAG_STEM="aqualoc_archaeo$(printf "%02d" "$((10#$SEQ))")_${START}_${END}"
    RUN_DIR_ROOT="$ROOT/logs/aqualoc_archaeo_vins"
    RUN_ARGS=(aqualoc_archaeo "$SEQ" "$START" "$END")
    ;;
  afrl)
    if [[ "${1:-}" == "fr" || "${1:-}" == "cave" ]]; then
      shift
    fi
    START="${1:?afrl [fr|cave] START_S DURATION_S [METHOD] [EVERY_N]}"
    DURATION="$2"
    METHOD="${3:-$METHOD_DEFAULT}"
    EVERY_N="${4:-2}"
    TAG_STEM="afrl_s${START}_d${DURATION}"
    RUN_DIR_ROOT="$ROOT/logs/afrl_cave_v31"
    RUN_ARGS=(afrl "$START" "$DURATION")
    ;;
  *)
    echo "unsupported dataset family: $DATASET_FAMILY" >&2
    exit 2
    ;;
esac

