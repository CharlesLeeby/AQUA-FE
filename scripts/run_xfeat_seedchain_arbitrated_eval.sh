#   AQUAFE_SEEDCHAIN_PROFILE=lineage_early_seed_scan RUN_VINS=0 bash scripts/run_xfeat_seedchain_arbitrated_eval.sh ntnu fjord_1 85 10 hybrid_xfeat 2
#   RUN_VINS=0 bash scripts/run_xfeat_seedchain_arbitrated_eval.sh aqualoc_archaeo 10 4960 5280 hybrid_xfeat 2
#   RUN_VINS=0 bash scripts/run_xfeat_seedchain_arbitrated_eval.sh aqualoc_real h07 1660 1740 hybrid_xfeat 2
#   RUN_VINS=0 bash scripts/run_xfeat_seedchain_arbitrated_eval.sh afrl 70 30 hybrid_xfeat 2
#   RUN_VINS=0 bash scripts/run_xfeat_seedchain_arbitrated_eval.sh cirs 575 30 hybrid_xfeat 1

